@pytest.mark.parametrize("outcomes", [
    ["fail"], ["error"], ["pass", "fail"], ["pass", "error"], ["fail", "pass"], ["pass"],
])
def test_close_needs_the_latest_result_at_current_inputs_to_pass(tmp_path, outcomes):
    built = build(tmp_path, "covered")
    revision = built.revision
    for outcome in outcomes:
        revision = ledger.record_result(
            built.dir, "abi-1", outcome=outcome, evidence="E1", inputs=INPUTS, expect_revision=revision,
        )
    if outcomes[-1] != "pass":
        assert_unchanged(
            built.dir, lambda: close(built.dir, revision), "refused",
            f"the latest result for abi-1 at the current inputs is {outcomes[-1]}, not pass",
        )
        return
    revision = close(built.dir, revision)
    assert record(built.dir)["state"] == "closed"
    assert record(built.dir)["closure"]["result"] == len(outcomes) - 1
    assert record(built.dir)["closure"]["closed_at"] == revision


