"""Owner-side obligation ledger tests against real ledger directories.

Failure modes: a stale expected revision, illegal transition or invalid
argument still writing; a second writer interleaving; a ledger in a symlinked,
shared or forbidden directory; a corrupt ledger being trusted or repaired;
closure without a passing latest result at the current inputs, or on missing,
changed or wrong-target evidence; a declared input change leaving covered or
closed obligations in place or discarding what it clears; a write, replace or
fsync failure or an interruption losing or half-writing the committed ledger;
leftover temp files being read; a view failure hiding a committed revision;
the view being read back as truth or dropping uncertainty; the ledger loading
the RE stack. Real files, locks, signals, resource limits and C1 evidence are
used. Only os.replace and os.fsync are substituted in-process, because they
cannot be made to fail, or to race a signal, on demand.
"""
