@contextlib.contextmanager
def sigint_at_fsync(monkeypatch, directory):
    """Send a real SIGINT to this thread from inside os.fsync of a file or of the directory.

    A signal delivered instead of held fails the test rather than the session.
    """
    def delivered(signum, frame):
        raise AssertionError("SIGINT was delivered during the commit instead of being held")
    previous = signal.signal(signal.SIGINT, delivered)
    real = os.fsync
    def fsync(fd):
        if stat.S_ISDIR(os.fstat(fd).st_mode) == directory:
            signal.pthread_kill(threading.main_thread().ident, signal.SIGINT)
        return real(fd)
    monkeypatch.setattr(os, "fsync", fsync)
    try:
        yield delivered
    finally:
        monkeypatch.setattr(os, "fsync", real)
        signal.signal(signal.SIGINT, previous)


def test_sigint_before_the_commit_leaves_the_ledger_unchanged_in_process(tmp_path, monkeypatch):
    built = build(tmp_path, "covered")
    with sigint_at_fsync(monkeypatch, directory=False) as handler:
        error = assert_unchanged(built.dir, lambda: ledger.add(
            built.dir, "abi-2", "second", expect_revision=built.revision,
        ), "interrupted", "interrupted")
        assert_signal_state_restored(handler)
    assert str(error) == f"interrupted; ledger unchanged at revision {built.revision}"


def test_sigint_after_the_commit_keeps_the_new_revision_in_process(tmp_path, monkeypatch):
    built = build(tmp_path, "covered")
