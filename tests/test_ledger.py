@pytest.mark.parametrize("dimension,new_id", [("specification", "spec-2"), ("unknown", "toolchain drift")])
def test_specification_or_unknown_change_reopens_everything_to_pending(tmp_path, dimension, new_id):
    built = build(tmp_path, "closed")
    revision = ledger.add(built.dir, "abi-2", "second", expect_revision=built.revision)
