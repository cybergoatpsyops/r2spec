TARGET = b"r2spec synthetic ledger target\n"
TARGET_SHA = hashlib.sha256(TARGET).hexdigest()
OTHER_SHA = hashlib.sha256(b"another target").hexdigest()
INPUTS = {
    "target": TARGET_SHA, "configuration": "flake-1", "specification": "spec-1", "tests": "tests-1",
}
STEPS = ("pending", "specified", "covered", "passed", "closed")


def inspect_evidence(path, target_sha):
    """Write the parts of a C1 r2spec.re.inspect/1 document that the ledger binds to."""
    path.write_text(json.dumps({
        "schema": "r2spec.re.inspect/1", "facts": {}, "unknowns": [],
        "target": {"sha256": target_sha, "confidence": "observed"},
    }))
    return path


def close(directory, revision, obligation_id="abi-1", **overrides):
    arguments = {
        "disposition": "accepted", "rationale": "pass at the current inputs",
        "limitations": ["first slice only"], "expect_revision": revision,
    }
    arguments.update(overrides)
    return ledger.close(directory, obligation_id, **arguments)


def advance(directory, test_file, revision, upto, obligation_id="abi-1"):
    steps = {
        "specified": lambda r: ledger.specify(directory, obligation_id, expect_revision=r),
        "covered": lambda r: ledger.cover(directory, obligation_id, [test_file], expect_revision=r),
        "passed": lambda r: ledger.record_result(
            directory, obligation_id, outcome="pass", evidence="E1", inputs=INPUTS, expect_revision=r,
        ),
        "closed": lambda r: close(directory, r, obligation_id),
    }
    for step in STEPS[1:STEPS.index(upto) + 1]:
        revision = steps[step](revision)
    return revision


def build(tmp_path, upto="covered", forbidden_roots=()):
    """A ledger with every input declared and obligation abi-1 advanced to upto."""
    directory = tmp_path / "ledger"
    evidence = inspect_evidence(tmp_path / "evidence.json", TARGET_SHA)
    test_file = tmp_path / "test_abi.py"
    test_file.write_text("def test_abi():\n    pass\n")
    revision = ledger.init(directory, forbidden_roots)
    for name, value in INPUTS.items():
        revision = ledger.change(directory, name, value, reason="initial", expect_revision=revision)
    revision = ledger.add(directory, "abi-1", "add() returns the wrapped sum", expect_revision=revision)
    revision = ledger.attach_evidence(
        directory, "abi-1", "E1", evidence, kind="re-inspect", expect_revision=revision,
    )
    revision = advance(directory, test_file, revision, upto)
    return SimpleNamespace(dir=directory, evidence=evidence, test_file=test_file, revision=revision)


def record(directory, obligation_id="abi-1"):
    return ledger.load(directory)[0]["obligations"][obligation_id]


def history(directory):
    return ledger.load(directory)[0]["history"]


def files(directory):
    """Every name and byte in the ledger directory."""
    return {path.name: path.read_bytes() for path in sorted(Path(directory).iterdir())}


def view_header(directory):
    return (Path(directory) / "LEDGER.md").read_text().splitlines()[0]


def expected_header(directory):
    data = (Path(directory) / "ledger.json").read_bytes()
    revision = json.loads(data)["revision"]
    return (
        f"<!-- GENERATED by r2spec from ledger.json revision {revision} "
        f"(sha256 {hashlib.sha256(data).hexdigest()}). NOT AUTHORITATIVE. "
        "Edits are ignored and overwritten. -->"
    )


def assert_unchanged(directory, call, kind, match):
    """The call fails with this kind and leaves every ledger byte as it was."""
    before = files(directory)
    with pytest.raises(LedgerError, match=match) as caught:
        call()
    assert caught.value.kind == kind
    assert not caught.value.committed
    assert files(directory) == before
    return caught.value


def move(obligation_id, old, new):
    return {"id": obligation_id, "from": old, "to": new}


# Storage: one private canonical document, one revision per commit.
def test_init_creates_private_ledger_and_view(tmp_path):
    directory = tmp_path / "ledger"
    assert ledger.init(directory) == 0
    assert stat.S_IMODE(directory.stat().st_mode) == 0o700
    assert list(files(directory)) == ["LEDGER.md", "ledger.json"]
    for name in ("LEDGER.md", "ledger.json"):
        assert stat.S_IMODE((directory / name).stat().st_mode) == 0o600
    document, revision, digest = ledger.load(directory)
    assert (document["schema"], revision) == ("r2spec.ledger/1", 0)
    assert document["inputs"] == dict.fromkeys(INPUTS)
    assert document["obligations"] == {}
    assert document["history"] == [{"detail": {}, "op": "init", "revision": 0, "transitions": []}]
    assert digest == hashlib.sha256((directory / "ledger.json").read_bytes()).hexdigest()
    assert view_header(directory) == expected_header(directory)


@pytest.mark.parametrize("case", ["directory", "file", "dangling symlink", "missing parent"])
def test_init_refuses_existing_path_or_missing_parent(tmp_path, case):
    directory = tmp_path / "ledger"
    if case == "directory":
        directory.mkdir()
    elif case == "file":
        directory.write_text("keep")
    elif case == "dangling symlink":
        directory.symlink_to(tmp_path / "missing")
    else:
        directory = tmp_path / "absent" / "ledger"
    before = sorted(tmp_path.rglob("*"))
    with pytest.raises(LedgerError) as caught:
        ledger.init(directory)
    assert caught.value.kind == "invocation"
    assert sorted(tmp_path.rglob("*")) == before


def test_each_mutation_commits_one_revision_with_its_history(tmp_path):
    built = build(tmp_path, "closed")
    document, revision, _ = ledger.load(built.dir)
    assert revision == built.revision == 10
    assert [entry["revision"] for entry in document["history"]] == list(range(11))
    assert [entry["op"] for entry in document["history"]] == [
        "init", "change", "change", "change", "change", "add", "attach_evidence",
        "specify", "cover", "record_result", "close",
    ]
    assert [moved for entry in document["history"] for moved in entry["transitions"]] == [
        move("abi-1", None, "pending"), move("abi-1", "pending", "specified"),
        move("abi-1", "specified", "covered"), move("abi-1", "covered", "closed"),
    ]
    assert document["inputs"] == {
        "target": {"id": TARGET_SHA, "since": 1}, "configuration": {"id": "flake-1", "since": 2},
        "specification": {"id": "spec-1", "since": 3}, "tests": {"id": "tests-1", "since": 4},
    }
    obligation = document["obligations"]["abi-1"]
    assert obligation["state"] == "closed"
    assert obligation["specification"] == "spec-1"
    assert obligation["evidence"] == {"E1": {
        "confidence": "observed", "kind": "re-inspect", "path": str(built.evidence.resolve()),
        "schema": "r2spec.re.inspect/1",
        "sha256": hashlib.sha256(built.evidence.read_bytes()).hexdigest(), "target_sha256": TARGET_SHA,
    }}
    assert obligation["coverage"] == {
        "tests": [{
            "path": str(built.test_file.resolve()),
            "sha256": hashlib.sha256(built.test_file.read_bytes()).hexdigest(),
        }],
        "tests_input": "tests-1",
    }
    assert obligation["results"] == [{
        "confidence": "reported", "evidence": "E1", "inputs": INPUTS, "outcome": "pass", "recorded_at": 9,
    }]
    assert obligation["closure"] == {
        "closed_at": 10, "disposition": "accepted", "inputs": INPUTS,
        "limitations": ["first slice only"], "rationale": "pass at the current inputs", "result": 0,
    }


