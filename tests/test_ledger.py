    assert after["closure"] is None
    assert (after["coverage"], after["results"]) == (before["coverage"], before["results"])
    assert ledger.load(built.dir)[0]["inputs"][dimension] == {"id": new_id, "since": revision}
    assert history(built.dir)[-1] == {
        "detail": {
            "affects": "all", "cleared": {"abi-1": {"closure": before["closure"]}},
            "dimension": dimension, "from": INPUTS[dimension], "reason": "rebuilt", "to": new_id,
        },
        "op": "change", "revision": revision, "transitions": [move("abi-1", "closed", "covered")],
    }
    assert_unchanged(built.dir, lambda: close(built.dir, revision), "refused", "no result at the current inputs")
    assert "stale inputs" in (built.dir / "LEDGER.md").read_text()


